"""Compile GLSL shaders to SPIR-V and embed them in src/generated/shaders_spv.h."""
import os, shutil, subprocess, sys, tempfile
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sh = os.path.join(root, "shaders")
tool = shutil.which("glslangValidator") or (os.path.join(os.environ.get("VULKAN_SDK", ""), "Bin", "glslangValidator.exe"))
names = ["mesh.vert", "mesh.frag", "id.frag", "line.vert", "line.frag", "bg.vert", "bg.frag", "grid.vert", "grid.frag"]
out = ["// Generated by tools/compile_shaders.py. Do not edit.", "#pragma once", "#include <cstdint>", "namespace kst::spv {"]
for n in names:
    var = n.replace(".", "_")
    tmp = os.path.join(tempfile.gettempdir(), var + ".spv")
    subprocess.check_call([tool, "-V", "--target-env", "vulkan1.3", "-I" + sh, os.path.join(sh, n), "-o", tmp])
    data = open(tmp, "rb").read()
    words = [int.from_bytes(data[i:i+4], "little") for i in range(0, len(data), 4)]
    body = ",".join(f"0x{w:08x}u" + ("\n" if (k + 1) % 8 == 0 else "") for k, w in enumerate(words))
    out.append(f"inline const uint32_t {var}[] = {{\n{body}}};")
out.append("}")
open(os.path.join(root, "src", "generated", "shaders_spv.h"), "w").write("\n".join(out) + "\n")
print("ok")
