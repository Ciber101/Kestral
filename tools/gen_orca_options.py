#!/usr/bin/env python3
"""Generates src/print/OrcaOptions.inc from OrcaSlicer's source: every setting's label, unit, tooltip,
choices and limits (libslic3r/PrintConfig.cpp) and how Orca lays them out in its process, filament and
printer tabs (slic3r/GUI/Tab.cpp). Run: python3 tools/gen_orca_options.py <orca source folder>"""
import re, sys, os

orca = sys.argv[1]
out_path = os.path.join(os.path.dirname(__file__), '..', 'src', 'print', 'OrcaOptions.inc')
pc = open(os.path.join(orca, 'src/libslic3r/PrintConfig.cpp'), encoding='utf-8').read()
tab = open(os.path.join(orca, 'src/slic3r/GUI/Tab.cpp'), encoding='utf-8').read()

STR = r'"(?:[^"\\]|\\.)*"'
def unescape(t):
    return re.sub(r'\\(u[0-9a-fA-F]{4}|n|t|"|\\|\')',
                  lambda m: chr(int(m.group(1)[1:], 16)) if m.group(1)[0] == 'u' else {'n': '\n', 't': '\t'}.get(m.group(1), m.group(1)), t)

def strings(s):
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    return ''.join(unescape(x[1:-1]) for x in re.findall(STR, s))

# ---- options
opts = {}
start = pc.index('void PrintConfigDef::init_common_params()')
end = pc.index('void PrintConfigDef::init_sla_params()')
body = pc[start:end]
for m in re.finditer(r'def\s*=\s*this->add(?:_nullable)?\(\s*"([a-z0-9_]+)"\s*,\s*(co\w+)\s*\)', body):
    key, typ = m.group(1), m.group(2)
    nxt = re.search(r'def\s*=\s*this->add', body[m.end():])
    seg = body[m.end(): m.end() + (nxt.start() if nxt else 4000)]
    def field(name):
        f = re.search(r'def->' + name + r'\s*=\s*((?:[^;"]|' + STR + r')*);', seg)
        return strings(f.group(1)) if f else ''
    def num(name):
        f = re.search(r'def->' + name + r'\s*=\s*(-?[0-9.eE+]+)\s*;', seg)
        return f.group(1) if f else ''
    if 'def->mode' in seg:
        t = seg.split('def->mode', 1)[1][:40]
        mode = 'develop' if 'comDevelop' in t else 'advanced' if 'comAdvanced' in t else 'simple'
    else:
        mode = 'simple'
    vals = [strings(x) for x in re.findall(r'def->enum_values\.(?:push|emplace)_back\(\s*(' + STR + r')\s*\)', seg)]
    labs = [strings(x) for x in re.findall(r'def->enum_labels\.(?:push|emplace)_back\(\s*_?L?\(?\s*(' + STR + r')\s*\)?\s*\)', seg)]
    opts[key] = dict(type=typ, label=field('label'), full=field('full_label'), side=field('sidetext'),
                     tip=field('tooltip'), cat=field('category'), mode=mode, vals=vals, labs=labs,
                     min=num('min'), max=num('max'))

# Choices shared with the top surface pattern.
for k, o in opts.items():
    if not o['vals'] and k in ('bottom_surface_pattern', 'internal_solid_infill_pattern') and 'top_surface_pattern' in opts:
        o['vals'], o['labs'] = opts['top_surface_pattern']['vals'], opts['top_surface_pattern']['labs']

# ---- layout
def tab_body(name):
    s = tab.index('void %s::build(' % name)
    e = tab.index('\nvoid ', s + 10)
    return tab[s:e]
layout = []
for tabname, fn in (('process', 'TabPrint'), ('filament', 'TabFilament'), ('printer', 'TabPrinter')):
    b = tab_body(fn)
    if fn == 'TabPrinter':
        s = tab.index('void TabPrinter::build_fff()')
        b = tab[s: tab.index('\nvoid ', s + 10)]
        # extruder pages are built elsewhere
        for fn2 in ('PageShp TabPrinter::build_kinematics_page()', 'void TabPrinter::build_unregular_pages('):
            s2 = tab.index(fn2)
            b += tab[s2: tab.index('\nvoid ', s2 + 10)]
    if fn == 'TabFilament':
        s2 = tab.index('void TabFilament::add_filament_overrides_page()')
        b = b.replace('add_filament_overrides_page();', tab[s2: tab.index('\nvoid ', s2 + 10)], 1)
    page = group = None
    seen = set()
    line = ''
    for m in re.finditer(r'add_options_page\(\s*(?:_?L\(\s*(' + STR + r')|page_name)|new_optgroup\(\s*_?L\(\s*(' + STR + r')|(?:append_single_option_line|get_option|append_option_line)\(\s*(' + STR + r')|(?:Line\s+\w+\s*=|\bline\s*=)\s*(?:Line)?\s*\{\s*_?L\(\s*(' + STR + r')|append_line\(', b):
        if m.group(0).startswith('add_options_page'): page = strings(m.group(1)) if m.group(1) else 'Extruder'; group = None; line = ''
        elif m.group(2): group = strings(m.group(2)); line = ''
        elif m.group(4): line = strings(m.group(4))
        elif m.group(0).startswith('append_line'): line = ''
        else:
            key = strings(m.group(3)).split('#')[0]
            if page and key in opts and (tabname, key) not in seen:
                seen.add((tabname, key))
                layout.append((tabname, page, group or '', key, line if m.group(0).startswith('get_option') else ''))

def c(s):
    s = s.replace('\u2103', '\u00b0C')   # the UI font has no single "degrees Celsius" sign
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '') + '"'

used = sorted(set(opts))
with open(out_path, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/gen_orca_options.py from OrcaSlicer\'s source (AGPL-3.0). Do not edit.\n')
    f.write('// key, type, label, full label, unit, tooltip, category, mode, choices (\\n separated), choice labels, min, max\n')
    f.write('static const OrcaOptionDef kOrcaOptions[] = {\n')
    for k in used:
        o = opts[k]
        f.write('    {%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s},\n' % (
            c(k), c(o['type']), c(o['label']), c(o['full']), c(o['side']), c(o['tip'][:1500]), c(o['cat']), c(o['mode']),
            c('\n'.join(o['vals'])), c('\n'.join(o['labs'])), c(o['min']), c(o['max'])))
    f.write('};\n\n// tab, page, group, key, line (the row a setting shares with others): the order OrcaSlicer shows them in\n')
    f.write('static const OrcaLayoutRow kOrcaLayout[] = {\n')
    for t, p, g, k, l in layout:
        f.write('    {%s, %s, %s, %s, %s},\n' % (c(t), c(p), c(g), c(k), c(l)))
    f.write('};\n')
print(len(used), 'options,', len(layout), 'layout rows ->', out_path)
